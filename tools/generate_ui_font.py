#!/usr/bin/env python3
"""Generate the fixed 8x16/16x16 glyph subset used by the LCD UI."""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


CHINESE_TEXT = (
    "电磁炮击靶系统距离发射状态待机方位仰角固定自动搜索往复扫描停止"
    "命令已发送控制器未接入队列满显示或触摸故障屏就绪运行完成"
    "设置清退确认取消范围请输入目标"
)


def render_rows(font_path: Path, char: str, width: int, size: int) -> list[int]:
    font = ImageFont.truetype(str(font_path), size=size)
    image = Image.new("L", (width, 16), color=0)
    draw = ImageDraw.Draw(image)
    bbox = draw.textbbox((0, 0), char, font=font)
    glyph_width = bbox[2] - bbox[0]
    glyph_height = bbox[3] - bbox[1]
    x = (width - glyph_width) // 2 - bbox[0]
    y = (16 - glyph_height) // 2 - bbox[1]
    draw.text((x, y), char, fill=255, font=font)

    rows: list[int] = []
    for row in range(16):
        bits = 0
        for column in range(width):
            bits <<= 1
            if image.getpixel((column, row)) >= 96:
                bits |= 1
        rows.append(bits)
    return rows


def emit_glyph(codepoint: int, width: int, rows: list[int]) -> str:
    values = ", ".join(f"0x{row:04X}U" for row in rows)
    return f"    {{0x{codepoint:04X}U, {width}U, {{{values}}}}},"


def generate(ascii_font: Path, chinese_font: Path, output: Path) -> None:
    glyphs: list[tuple[int, int, list[int]]] = []
    for codepoint in range(32, 127):
        glyphs.append(
            (codepoint, 8, render_rows(ascii_font, chr(codepoint), 8, 14))
        )
    glyphs.append((ord("°"), 8, render_rows(ascii_font, "°", 8, 14)))
    for char in sorted(set(CHINESE_TEXT), key=ord):
        glyphs.append((ord(char), 16, render_rows(chinese_font, char, 16, 16)))
    glyphs.sort(key=lambda glyph: glyph[0])

    entries = "\n".join(emit_glyph(*glyph) for glyph in glyphs)
    source = f'''/* Generated by tools/generate_ui_font.py. Do not edit manually. */
#include "ui_font.h"

#include <stddef.h>

static const ui_font_glyph_t s_glyphs[] = {{
{entries}
}};

const ui_font_glyph_t *ui_font_find(uint32_t codepoint)
{{
    size_t low = 0U;
    size_t high = sizeof(s_glyphs) / sizeof(s_glyphs[0]);

    while (low < high) {{
        const size_t middle = low + (high - low) / 2U;
        if (s_glyphs[middle].codepoint == codepoint) {{
            return &s_glyphs[middle];
        }}
        if (s_glyphs[middle].codepoint < codepoint) {{
            low = middle + 1U;
        }} else {{
            high = middle;
        }}
    }}

    if (codepoint != (uint32_t)'?') {{
        return ui_font_find((uint32_t)'?');
    }}
    return NULL;
}}

bool ui_font_utf8_next(const char **cursor, uint32_t *codepoint)
{{
    const unsigned char *text;
    uint32_t value;
    uint8_t length;
    uint8_t index;

    if ((cursor == NULL) || (*cursor == NULL) || (codepoint == NULL)) {{
        return false;
    }}
    text = (const unsigned char *)*cursor;
    if (*text == 0U) {{
        return false;
    }}

    if (text[0] < 0x80U) {{
        *codepoint = text[0];
        *cursor += 1;
        return true;
    }}
    if ((text[0] & 0xE0U) == 0xC0U) {{
        value = text[0] & 0x1FU;
        length = 2U;
    }} else if ((text[0] & 0xF0U) == 0xE0U) {{
        value = text[0] & 0x0FU;
        length = 3U;
    }} else if ((text[0] & 0xF8U) == 0xF0U) {{
        value = text[0] & 0x07U;
        length = 4U;
    }} else {{
        *codepoint = (uint32_t)'?';
        *cursor += 1;
        return true;
    }}

    for (index = 1U; index < length; ++index) {{
        if ((text[index] & 0xC0U) != 0x80U) {{
            *codepoint = (uint32_t)'?';
            *cursor += 1;
            return true;
        }}
        value = (value << 6U) | (text[index] & 0x3FU);
    }}

    *codepoint = value;
    *cursor += length;
    return true;
}}

uint16_t ui_font_text_width(const char *text)
{{
    uint16_t width = 0U;
    uint32_t codepoint;

    while (ui_font_utf8_next(&text, &codepoint)) {{
        const ui_font_glyph_t *glyph = ui_font_find(codepoint);
        if (glyph != NULL) {{
            width = (uint16_t)(width + glyph->width);
        }}
    }}
    return width;
}}
'''
    output.write_text(source, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--ascii-font", type=Path, default=Path(r"C:\Windows\Fonts\consola.ttf")
    )
    parser.add_argument(
        "--chinese-font", type=Path, default=Path(r"C:\Windows\Fonts\msyh.ttc")
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("Application/ui/ui_font.c"),
    )
    args = parser.parse_args()
    generate(args.ascii_font, args.chinese_font, args.output)


if __name__ == "__main__":
    main()
